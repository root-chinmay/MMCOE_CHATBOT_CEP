// Gemini API integration for answering general, non-college questions

async function askGemini(prompt, clientApiKey = null) {
  const apiKey = clientApiKey || process.env.GEMINI_API_KEY;

  if (!apiKey) {
    return {
      success: false,
      isFallback: true,
      html: `
        <div class="rs">
          <span class="rt">🤖 AI General Knowledge Assistant</span>
          <p style="color:var(--text-main);font-size:.9rem;line-height:1.6;margin-bottom:10px;">
            You asked: <em>"${prompt.replace(/</g, '&lt;').replace(/>/g, '&gt;')}"</em>
          </p>
          <div class="note">
            ℹ️ <strong>Gemini AI Integration Ready:</strong><br>
            This question appears to be outside the MMCOE college domain. To enable real-time responses powered by Google Gemini AI, please set your <code>GEMINI_API_KEY</code> in your <code>.env</code> file or in your Vercel Environment Variables settings!
            <br><br>
            Get a free API key at: <a href="https://aistudio.google.com/" target="_blank" style="color:var(--gold-bright);text-decoration:underline;">Google AI Studio</a>.
          </div>
        </div>
      `
    };
  }

  // System instruction to maintain polite MMCOE Assistant persona
  const systemPrompt = `You are MMCOE AI Assistant, a smart, polite, and helpful assistant designed for students and visitors of Marathwada Mitra Mandal's College of Engineering (MMCOE), Pune.
When answering general questions (coding, engineering, math, science, general advice, etc.):
1. Be concise, direct, helpful, and highly clear.
2. If providing code, use clear markdown blocks with language tags.
3. Keep a warm, encouraging tone.
4. If asked who created you, say you are the MMCOE AI ChatBot created by Chinmay Rajendra Amodkar.`;

  try {
    const url = `https://generativelanguage.googleapis.com/v1beta/models/gemini-1.5-flash:generateContent?key=${apiKey}`;

    const payload = {
      contents: [
        {
          role: 'user',
          parts: [
            { text: `${systemPrompt}\n\nUser Question:\n${prompt}` }
          ]
        }
      ],
      generationConfig: {
        temperature: 0.7,
        maxOutputTokens: 1024,
      }
    };

    const response = await fetch(url, {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json'
      },
      body: JSON.stringify(payload)
    });

    if (!response.ok) {
      const errText = await response.text();
      console.error('[Gemini API] Request failed:', response.status, errText);
      return {
        success: false,
        error: `Gemini API returned status ${response.status}`,
        html: `
          <div class="rs">
            <span class="rt">🤖 Gemini AI Notice</span>
            <p style="color:var(--text-sub);font-size:.88rem;">
              Could not fetch live response from Gemini API (Status: ${response.status}). Please verify that your <code>GEMINI_API_KEY</code> is valid.
            </p>
          </div>
        `
      };
    }

    const data = await response.json();
    const candidateText = data?.candidates?.[0]?.content?.parts?.[0]?.text;

    if (!candidateText) {
      return {
        success: false,
        html: `<div class="rs"><span class="rt">🤖 Notice</span><p>No response generated by Gemini model.</p></div>`
      };
    }

    // Convert basic markdown formatting to clean HTML for display
    const formattedHtml = formatMarkdownToHtml(candidateText);

    return {
      success: true,
      text: candidateText,
      html: `
        <div class="rs gemini-response">
          <div style="display:flex;align-items:center;gap:6px;margin-bottom:8px;">
            <span style="font-size:1rem;">✨</span>
            <span class="rt" style="margin:0;">Gemini AI Answer</span>
            <span style="font-size:.65rem;background:rgba(200,150,12,0.18);color:var(--gold-bright);border:1px solid rgba(200,150,12,0.3);padding:1px 6px;border-radius:4px;margin-left:auto;">General Topic</span>
          </div>
          <div class="gemini-content" style="color:var(--text-main);font-size:.89rem;line-height:1.65;">
            ${formattedHtml}
          </div>
        </div>
      `
    };
  } catch (err) {
    console.error('[Gemini API] Fetch exception:', err);
    return {
      success: false,
      error: err.message,
      html: `
        <div class="rs">
          <span class="rt">⚠️ Connection Notice</span>
          <p style="color:var(--text-sub);font-size:.88rem;">An error occurred while contacting Gemini AI: ${err.message}</p>
        </div>
      `
    };
  }
}

function formatMarkdownToHtml(text) {
  let output = text
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;');

  // Code blocks: ```lang code ```
  output = output.replace(/```([a-zA-Z0-9_-]*)\n([\s\S]*?)```/g, (match, lang, code) => {
    return `<pre style="background:rgba(0,0,0,0.5);border:1px solid rgba(255,255,255,0.1);padding:12px;border-radius:8px;overflow-x:auto;margin:10px 0;"><code style="font-family:monospace;font-size:.82rem;color:#e2e8f0;">${code}</code></pre>`;
  });

  // Inline code: `code`
  output = output.replace(/`([^`]+)`/g, '<code style="background:rgba(255,255,255,0.08);padding:2px 6px;border-radius:4px;font-family:monospace;font-size:.85rem;color:var(--gold-bright);">$1</code>');

  // Bold: **text**
  output = output.replace(/\*\*([^*]+)\*\*/g, '<strong>$1</strong>');

  // Italics: *text*
  output = output.replace(/\*([^*]+)\*/g, '<em>$1</em>');

  // Headings
  output = output.replace(/^### (.*$)/gim, '<h4 style="margin:10px 0 4px;color:var(--gold-bright);font-size:.95rem;">$1</h4>');
  output = output.replace(/^## (.*$)/gim, '<h3 style="margin:12px 0 6px;color:var(--text-main);font-size:1.05rem;">$1</h3>');
  output = output.replace(/^# (.*$)/gim, '<h2 style="margin:14px 0 8px;color:var(--text-main);font-size:1.15rem;">$1</h2>');

  // Bullet items
  output = output.replace(/^\s*[-*]\s+(.*)$/gim, '<li style="margin-bottom:4px;">$1</li>');
  output = output.replace(/(<li.*<\/li>)/s, '<ul style="padding-left:18px;margin:8px 0;">$1</ul>');

  // Paragraph line breaks
  output = output.replace(/\n\n/g, '<br><br>');
  output = output.replace(/\n/g, '<br>');

  return output;
}

module.exports = {
  askGemini
};
